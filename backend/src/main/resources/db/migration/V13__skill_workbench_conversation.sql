-- Skill workbench sessions: conversation / message / task process events, plus
-- the conversation binding on skill_optimize_task.
--
-- Ported from kmplm V36.
-- Design notes:
--  * events are durable in the DB; SSE is only a push accelerator. Clients
--    re-sync after a disconnect via messages?after=<seq>.
--  * conversation is bound to Skill@version; slug stores the skill identifier.

CREATE TABLE skill_conversation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(128) NOT NULL,
    version_id BIGINT NOT NULL REFERENCES skill_version(id) ON DELETE CASCADE,
    title VARCHAR(512),
    created_by VARCHAR(128),
    created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(3) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_skill_conversation_slug_version
    ON skill_conversation (slug, version_id);

-- Message: seq is monotonic within a conversation; content is plain text or a
-- JSON payload depending on msg_type.
CREATE TABLE skill_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES skill_conversation(id) ON DELETE CASCADE,
    seq INTEGER NOT NULL,
    role VARCHAR(16) NOT NULL,
    msg_type VARCHAR(32) NOT NULL,
    content TEXT NOT NULL,
    related_task_id BIGINT REFERENCES skill_optimize_task(id) ON DELETE SET NULL,
    related_candidate_id BIGINT REFERENCES skill_optimize_candidate(id) ON DELETE SET NULL,
    created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_skill_message_role CHECK (role IN ('user', 'assistant', 'system')),
    CONSTRAINT ck_skill_message_type CHECK (
        msg_type IN ('text', 'process_event', 'candidate_card', 'action_card')
    )
);

CREATE INDEX idx_skill_message_conversation_seq
    ON skill_message (conversation_id, seq);

-- Task process event: payload_json carries LLM duration, httpStatus, response
-- digest, per-gate results; raw responses are truncated on write.
CREATE TABLE skill_task_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES skill_optimize_task(id) ON DELETE CASCADE,
    stage VARCHAR(64) NOT NULL,
    level VARCHAR(16) NOT NULL DEFAULT 'info',
    payload_json TEXT,
    created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_skill_task_event_level CHECK (level IN ('info', 'warn', 'error'))
);

CREATE INDEX idx_skill_task_event_task
    ON skill_task_event (task_id, created_at);

-- Bind an optimize task to the conversation that drives it (stepwise advance).
ALTER TABLE skill_optimize_task
    ADD COLUMN IF NOT EXISTS conversation_id BIGINT
        REFERENCES skill_conversation(id) ON DELETE SET NULL;
