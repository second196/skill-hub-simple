-- Skill optimize ReAct engine: trajectory steps / workspace staging files, plus
-- ReAct-related extensions on optimize task, candidate and quality config.
--
-- Ported from kmplm V39.
-- Design notes:
--  * steps (thought/action/observation) are persisted as they run so a broken
--    client can rebuild the trace from the DB after reconnecting.
--  * staging rows snapshot oversized workspace files; crash recovery rebuilds
--    the workspace by (task_id, path).

-- ReAct trajectory steps.
CREATE TABLE skill_react_step (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES skill_optimize_task(id) ON DELETE CASCADE,
    step_no INTEGER NOT NULL,
    thought TEXT,
    action_type VARCHAR(64),
    action_json TEXT,
    observation_json TEXT,
    duration_ms BIGINT,
    token_estimate INTEGER,
    created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_skill_react_step_task_step
    ON skill_react_step (task_id, step_no);

-- Workspace staging: per-file snapshot when a single file exceeds the inline
-- limit.
CREATE TABLE skill_react_staging (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES skill_optimize_task(id) ON DELETE CASCADE,
    path VARCHAR(512) NOT NULL,
    content TEXT,
    created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_skill_react_staging_task_path
    ON skill_react_staging (task_id, path);

-- Optimize task extension: ReAct state snapshot (workspace manifest + hashes +
-- cursor, or an inline small snapshot) / interaction mode / engine dispatch
-- (existing and default rows use 'react').
ALTER TABLE skill_optimize_task
    ADD COLUMN IF NOT EXISTS react_state_json TEXT,
    ADD COLUMN IF NOT EXISTS react_mode VARCHAR(24),
    ADD COLUMN IF NOT EXISTS engine VARCHAR(16) NOT NULL DEFAULT 'react';

-- Optimize candidate extension: measured gate evidence digest and whether the
-- upstream response was truncated.
ALTER TABLE skill_optimize_candidate
    ADD COLUMN IF NOT EXISTS evidence_summary_json TEXT,
    ADD COLUMN IF NOT EXISTS truncated BOOLEAN NOT NULL DEFAULT FALSE;

-- Quality config extension: whether React optimization requires measured gates
-- (default true).
ALTER TABLE skill_quality_config
    ADD COLUMN IF NOT EXISTS react_require_measured_gates BOOLEAN NOT NULL DEFAULT TRUE;
