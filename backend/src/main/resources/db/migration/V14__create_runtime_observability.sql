    ON runtime_event (scope_id, trace_id, occurred_at, event_id);
CREATE INDEX idx_runtime_event_invocation_time
    ON runtime_event (scope_id, invocation_id, occurred_at, event_id)
    WHERE invocation_id IS NOT NULL;
CREATE INDEX idx_runtime_event_version_time
    ON runtime_event (scope_id, version_digest, occurred_at DESC, event_id)
    WHERE version_digest IS NOT NULL;

