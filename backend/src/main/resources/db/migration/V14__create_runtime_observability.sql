CREATE TABLE telemetry_ingest_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id VARCHAR(128) NOT NULL,
    actor_id VARCHAR(128) NOT NULL,
    token_id VARCHAR(128) NOT NULL,
    scope_id BIGINT NOT NULL REFERENCES governance_scope (id),
    runtime_key VARCHAR(64) NOT NULL,
    payload_digest CHAR(64) NOT NULL,
    received_count INT NOT NULL,
    accepted_count INT NOT NULL DEFAULT 0,
    duplicate_count INT NOT NULL DEFAULT 0,
    rejected_count INT NOT NULL DEFAULT 0,
    status VARCHAR(32) NOT NULL,
    error_summary JSONB NOT NULL DEFAULT '{}'::jsonb,
    received_at TIMESTAMP(3) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP(3) WITH TIME ZONE,
    CONSTRAINT uk_telemetry_batch_request UNIQUE (request_id),
    CONSTRAINT ck_telemetry_batch_payload_digest CHECK (payload_digest ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_telemetry_batch_counts CHECK (
        received_count >= 0 AND accepted_count >= 0 AND duplicate_count >= 0 AND rejected_count >= 0
    )
);

CREATE TABLE runtime_event_dedup (
    event_id VARCHAR(128) PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES telemetry_ingest_batch (id),
    occurred_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE runtime_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    event_id VARCHAR(128) NOT NULL,
    batch_id BIGINT NOT NULL REFERENCES telemetry_ingest_batch (id),
    schema_version VARCHAR(32) NOT NULL,
    event_type VARCHAR(64) NOT NULL,
    scope_id BIGINT NOT NULL REFERENCES governance_scope (id),
    runtime_key VARCHAR(64) NOT NULL,
    runtime_version VARCHAR(64) NOT NULL,
    tracker_version VARCHAR(64),
    session_id VARCHAR(128) NOT NULL,
    trace_id VARCHAR(128) NOT NULL,
    span_id VARCHAR(128) NOT NULL,
    parent_span_id VARCHAR(128),
    sequence BIGINT NOT NULL,
    agent_id VARCHAR(128),
    parent_agent_id VARCHAR(128),
    model_name VARCHAR(128),
    tool_name VARCHAR(128),
    mcp_server VARCHAR(128),
    skill_name VARCHAR(128),
    version_digest CHAR(64),
    invocation_id VARCHAR(128),
    trigger_type VARCHAR(64),
    status VARCHAR(32) NOT NULL,
    duration_ms BIGINT,
    input_tokens BIGINT,
    output_tokens BIGINT,
    cost NUMERIC(20,8),
    version_unknown BOOLEAN NOT NULL DEFAULT FALSE,
    version_unknown_reason VARCHAR(256),
    attributes JSONB NOT NULL DEFAULT '{}'::jsonb,
    missing_fields JSONB NOT NULL DEFAULT '[]'::jsonb,
    privacy_actions JSONB NOT NULL DEFAULT '[]'::jsonb,
    occurred_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,
    received_at TIMESTAMP(3) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (occurred_at, id),
    CONSTRAINT ck_runtime_event_sequence CHECK (sequence >= 0),
    CONSTRAINT ck_runtime_event_duration CHECK (duration_ms IS NULL OR duration_ms >= 0),
    CONSTRAINT ck_runtime_event_tokens CHECK (
        (input_tokens IS NULL OR input_tokens >= 0) AND (output_tokens IS NULL OR output_tokens >= 0)
    ),
    CONSTRAINT ck_runtime_event_version CHECK (
        (version_unknown = TRUE AND version_digest IS NULL AND version_unknown_reason IS NOT NULL)
        OR (version_unknown = FALSE AND version_digest ~ '^[0-9a-f]{64}$')
    )
) PARTITION BY RANGE (occurred_at);

DO $$
DECLARE
    partition_month DATE;
    next_month DATE;
    partition_name TEXT;
    month_offset INT;
BEGIN
    FOR month_offset IN 0..2 LOOP
        partition_month := (
            date_trunc('month', CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
            + (month_offset || ' month')::INTERVAL
        )::DATE;
        next_month := (partition_month + INTERVAL '1 month')::DATE;
        partition_name := 'runtime_event_' || to_char(partition_month, 'YYYY_MM');
        EXECUTE format(
            'CREATE TABLE %I PARTITION OF runtime_event FOR VALUES FROM (%L) TO (%L)',
            partition_name,
            partition_month::TEXT || ' 00:00:00+00',
            next_month::TEXT || ' 00:00:00+00'
        );
    END LOOP;
END $$;

