-- System settings: AI model runtime config (analysis/optimize) so admins can
-- switch endpoint/model at runtime instead of relying on application.yml.
--
-- Ported from kmplm V32 + V37 + V38 in final state: context_window replaces
-- daily_token_budget (V37), reasoning_effort added (V38). Single-row table,
-- enforced by a unique index on the constant expression.
CREATE TABLE sys_ai_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    endpoint VARCHAR(512) NOT NULL DEFAULT '',
    api_key VARCHAR(512) NOT NULL DEFAULT '',
    model VARCHAR(128) NOT NULL DEFAULT 'gpt-4.1-mini',
    embedding_model VARCHAR(128) NOT NULL DEFAULT 'text-embedding-3-small',
    timeout_ms INT NOT NULL DEFAULT 30000,
    max_tokens INT NOT NULL DEFAULT 2000,
    -- max context window (tokens) of the configured model (V37).
    context_window INTEGER NOT NULL DEFAULT 128000,
    -- reasoning effort (low|medium|high or NULL/empty = omit the parameter and
    -- let the model/gateway decide) (V38).
    reasoning_effort VARCHAR(16),
    updated_by VARCHAR(128),
    updated_at TIMESTAMP(3) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Singleton row.
CREATE UNIQUE INDEX uk_sys_ai_config_singleton ON sys_ai_config ((true));
