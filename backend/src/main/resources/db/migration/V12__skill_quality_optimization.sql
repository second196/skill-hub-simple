-- Skill quality analysis and optimization: report / optimize task / candidate /
-- quality config.
--
-- Ported from kmplm V31 (tables) + V35 (progress fields) + V40 (target scope);
-- progress and target-scope columns are folded into CREATE TABLE because these
-- tables are new here, and run_mode/target_issue_ids are defined upfront so the
-- status machine is complete in one place (conversation_id is added in V13,
-- after skill_conversation exists).
--
-- Design notes:
--  * report rows are per (skill_id, version_id); the newest row is the active report.
--  * status machine: queued -> running -> gated_pass/pending_review -> adopted;
--    running -> waiting_input (stepwise) | gated_fail -> rejected / queued.
--  * quality config is key-value JSONB; service layer falls back to constants.

-- One analysis report: L1 file checks / L2 writing scores / L3 observed usage
-- plus the overall conclusion.
CREATE TABLE skill_quality_report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id BIGINT NOT NULL REFERENCES skill(id) ON DELETE CASCADE,
    version_id BIGINT NOT NULL REFERENCES skill_version(id) ON DELETE CASCADE,
    l1_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    l2_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    l3_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    overall_score NUMERIC(6, 2),
    conclusion VARCHAR(32),
    method_note VARCHAR(512),
    rule_version VARCHAR(64),
    created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_skill_quality_report_lookup
    ON skill_quality_report (skill_id, version_id, created_at DESC);

-- Optimize task: mode=repair (hard-defect fix) | edit (bounded edit).
CREATE TABLE skill_optimize_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id BIGINT NOT NULL REFERENCES skill(id) ON DELETE CASCADE,
    version_id BIGINT NOT NULL REFERENCES skill_version(id) ON DELETE CASCADE,
    mode VARCHAR(16) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'queued',
    priority_list_json JSONB NOT NULL DEFAULT '[]'::jsonb,
    inputs_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    fail_reason VARCHAR(1024),
    -- run mode: auto runs to completion; stepwise pauses at waiting_input.
    run_mode VARCHAR(16) NOT NULL DEFAULT 'auto',
    target_issue_ids_json TEXT,
    -- progress surfaced to the workbench UI (V35).
    progress_stage VARCHAR(32) NOT NULL DEFAULT 'queued',
    progress_percent INTEGER NOT NULL DEFAULT 0,
    progress_message VARCHAR(512) NOT NULL DEFAULT '等待后台执行',
    -- frozen optimization scope so completion does not depend on model text (V40).
    target_scope_json TEXT,
    created_by VARCHAR(128),
    created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(3) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_skill_optimize_task_mode CHECK (mode IN ('repair', 'edit')),
    CONSTRAINT ck_skill_optimize_task_status CHECK (
        status IN ('queued', 'running', 'waiting_input', 'gated_pass',
                   'pending_review', 'gated_fail', 'adopted', 'rejected')
    ),
    CONSTRAINT ck_skill_optimize_task_run_mode CHECK (run_mode IN ('auto', 'stepwise'))
);

CREATE INDEX idx_skill_optimize_task_skill ON skill_optimize_task (skill_id, created_at DESC);
CREATE INDEX idx_skill_optimize_task_status ON skill_optimize_task (status);

-- Optimize candidate: gate results (gates_json) and paired comparison
-- (paired_json) live on the candidate card.
CREATE TABLE skill_optimize_candidate (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES skill_optimize_task(id) ON DELETE CASCADE,
    summary VARCHAR(2048),
    diff_text TEXT,
    edits_json JSONB NOT NULL DEFAULT '[]'::jsonb,
    gates_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    paired_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    decision VARCHAR(16) NOT NULL DEFAULT 'pending',
    decision_reason VARCHAR(1024),
    decided_by VARCHAR(128),
    decided_at TIMESTAMP(3) WITH TIME ZONE,
    result_version_id BIGINT REFERENCES skill_version(id),
    result_version_label VARCHAR(64),
    -- coverage of the frozen target scope (V40).
    coverage_json TEXT,
    created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(3) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_skill_optimize_candidate_decision CHECK (
        decision IN ('pending', 'adopted', 'rejected')
    )
);

CREATE INDEX idx_skill_optimize_candidate_task ON skill_optimize_candidate (task_id, created_at DESC);
CREATE INDEX idx_skill_optimize_candidate_decision ON skill_optimize_candidate (decision);

-- Weight and threshold config: key-value, value is JSONB (scalar or object);
-- missing keys fall back to service-layer constants.
-- Defaults: w1/w2/w3=0.2/0.4/0.4, optimizeThreshold/watchUpper=70/85,
--           minImprovement/maxRegression=0.02/0.02, editBudget=4, pairedN=3,
--           autoAccept=false.
CREATE TABLE skill_quality_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_key VARCHAR(64) NOT NULL,
    config_value JSONB NOT NULL DEFAULT 'null'::jsonb,
    description VARCHAR(512),
    updated_at TIMESTAMP(3) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_skill_quality_config_key UNIQUE (config_key)
);

